def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    service_ids = {s[0] for s in SERVICES}
    context_ids = {c["id"] for c in CONTEXTS}

    services = [
        dict(id=s[0], name=s[0], context=s[1], kind=s[2], tier=s[3], responsibility=s[4],
             datastore=s[5], scaling=s[6])
        for s in SERVICES
    ]

    events = [
        dict(name=e[0], version=int(e[0].rsplit(".v", 1)[1]), producer=e[1],
             consumers_contexts=e[2], partition_key=e[3], contains_phi=e[4],
             retention_days=e[5], description=e[6])
        for e in EVENTS
    ]

    for event in events:
        assert event["producer"] in service_ids, event
        for target in event["consumers_contexts"]:
            assert target in context_ids or target in service_ids, (event["name"], target)

    for context in CONTEXTS:
        for svc in context["services"]:
            assert svc in service_ids, (context["id"], svc)
        for svc in context["services"]:
            assert any(s["id"] == svc and s["context"] == context["id"] for s in services), svc

    # Producer services must declare a context that publishes their events.
    for event in events:
        producer_context = next(s["context"] for s in services if s["id"] == event["producer"])
        ctx = next(c for c in CONTEXTS if c["id"] == producer_context)
        assert event["name"] in ctx["publishes"], (event["name"], producer_context)

    with open(os.path.join(OUT, "contexts.json"), "w", encoding="utf-8") as fh:
        json.dump(CONTEXTS, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    with open(os.path.join(OUT, "services.json"), "w", encoding="utf-8") as fh:
        json.dump(services, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    with open(os.path.join(OUT, "events.json"), "w", encoding="utf-8") as fh:
        json.dump(events, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"contexts={len(CONTEXTS)} services={len(services)} events={len(events)}")


if __name__ == "__main__":
    main()
